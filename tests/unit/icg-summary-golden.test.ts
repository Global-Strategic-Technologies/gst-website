describe('ICG score context, in full', () => {
  it('below, within and above a stage range, and no stage', () => {
    expect([
      contextualizeScore(10, 'pre-series-b'),
      contextualizeScore(40, 'series-bc'),
      contextualizeScore(80, 'pe-backed'),
      contextualizeScore(65, 'enterprise'),
      contextualizeScore(50),
    ]).toMatchInlineSnapshot(`
      [
        "Your score of 10 is below the typical range for Pre-Series B companies (15–35)",
        "Your score of 40 is within the typical range for Series B-C companies (30–55)",
        "Your score of 80 is above the typical range for PE-backed 2+ yr companies (45–70)",
        "Your score of 65 is within the typical range for Enterprise companies (65–90)",
        null,
      ]
    `);
  });
});
