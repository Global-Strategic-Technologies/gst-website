import { calculateResults, getRecommendations, DEFAULT_STATE } from '../../src/utils/icg-engine';
import {
  buildSummaryText,
  contextualizeScore,
} from '../../src/scripts/infrastructure-cost-governance/logic';
import type { ICGState } from '../../src/utils/icg-engine';
import { DOMAINS } from '../../src/data/infrastructure-cost-governance/domains';
import { RECOMMENDATIONS } from '../../src/data/infrastructure-cost-governance/recommendations';

const URL = 'https://globalstrategic.tech/hub/tools/infrastructure-cost-governance/?s=abc';

function stateWith(score: (domainId: string, i: number) => number): ICGState {
  const answers: Record<string, number> = {};
  for (const d of DOMAINS) d.questions.forEach((q, i) => (answers[q.id] = score(d.id, i)));
  return { ...DEFAULT_STATE, answers };
}

function summary(state: ICGState, url?: string): string {
  const result = calculateResults(state, DOMAINS);
  const recs = getRecommendations(state, RECOMMENDATIONS);
  return buildSummaryText(state, result, DOMAINS, recs, url);
}

